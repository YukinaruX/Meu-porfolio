async page => {
  page.setDefaultTimeout(20000);
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const evidence = 'docs/private/';
  const baseUrl = new URL(page.url()).origin;
  const results = { desktop: {}, mobile: {}, accessibility: [] };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(baseUrl, { waitUntil: 'networkidle' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => document.fonts.ready);
  await page.getByRole('heading', { name: 'Sua próxima ideia. Pronta para o mundo.' }).waitFor({ state: 'visible' });
  await page.waitForFunction(() => [...document.querySelectorAll('.hero-copy > div')].every(el => Number(getComputedStyle(el).opacity) > 0.99));
  await page.screenshot({ path: evidence + 'react-hero-desktop.png' });
  assert(await page.evaluate(() => getComputedStyle(document.body).backgroundColor === 'rgb(0, 0, 0)'), 'Page background must be pure black');
  assert(await page.getByText('Desenvolvedor & fundador da A-NFC', { exact: true }).isVisible(), 'Founder positioning must be visible in hero');
  assert(await page.getByRole('button', { name: /pausar|retomar|pause|resume/i }).count() === 0, 'Motion controls must be absent');
  results.desktop.motionControlsRemoved = true;
  await page.locator('#projetos').scrollIntoViewIfNeeded();
  for (const image of await page.locator('.showcase-capture img').all()) {
    await image.evaluate(el => { el.loading = 'eager'; return el.decode(); });
  }
  const track = page.locator('.showcase-track');
  await page.getByRole('button', { name: 'Próximos projetos', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.showcase-track').scrollLeft > 100);
  results.desktop.carousel = { next: true };
  await track.focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(() => document.querySelector('.showcase-track').scrollLeft < 5);
  const firstCard = page.locator('.showcase-card').first();
  await firstCard.locator('.showcase-identity').evaluate(el => window.scrollBy(0, el.getBoundingClientRect().top - 140));
  const identity = await firstCard.locator('.showcase-identity').boundingBox();
  await page.mouse.move(identity.x + 300, identity.y + 20);
  await page.mouse.down();
  await page.mouse.move(identity.x + 10, identity.y + 20, { steps: 20 });
  await page.mouse.up();
  assert(await track.evaluate(el => el.scrollLeft > 100), 'Project strip must drag with mouse');
  await track.evaluate(el => { el.scrollTo({ left: 0, behavior: 'instant' }); });
  await page.waitForFunction(() => document.querySelector('.showcase-track').scrollLeft < 5);
  results.desktop.carousel.mouseDrag = true;
  await firstCard.getByRole('button', { name: 'Próxima tela', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.showcase-card .carousel-slide[data-current="true"]').querySelector('.showcase-screen--mobile'));
  const innerPreview = firstCard.locator('.carousel-slide[data-current="true"] .showcase-capture');
  await innerPreview.evaluate(el => { el.scrollTop = 250; });
  assert(await innerPreview.evaluate(el => el.scrollTop > 0), 'Embedded screenshot must scroll');
  await innerPreview.evaluate(el => { el.scrollTop = 0; });
  const previewBox = await innerPreview.boundingBox();
  await page.mouse.move(previewBox.x + 60, previewBox.y + 200);
  await page.mouse.down();
  await page.mouse.move(previewBox.x + 60, previewBox.y + 50, { steps: 15 });
  await page.mouse.up();
  assert(await innerPreview.evaluate(el => el.scrollTop > 50), 'Capture must support vertical mouse dragging');
  await firstCard.getByRole('button', { name: 'Tela anterior', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.showcase-card .carousel-slide[data-current="true"]').querySelector('.showcase-screen--desktop'));
  results.desktop.carousel.screens = true;
  results.desktop.carousel.verticalScroll = true;
  const captureStyle = '.site-header, .skip-link { visibility: hidden !important; }';
  await page.locator('#projetos').screenshot({ path: evidence + 'react-projects-desktop.png', style: captureStyle });
  await page.getByRole('link', { name: 'Explorar projeto Alice Vieira', exact: true }).first().click();
  await page.locator('dialog[open]').waitFor();
  assert(await page.evaluate(() => document.body.style.overflow === 'hidden'), 'Reader must lock background scroll');
  await page.locator('.project-dialog').getByRole('button', { name: 'Celular', exact: true }).click();
  await page.locator('.reader-canvas img').evaluate(el => el.decode());
  assert(await page.locator('.project-dialog').getByRole('button', { name: 'Celular', exact: true }).getAttribute('aria-pressed') === 'true', 'Mobile mode must be selected');
  assert(page.url().endsWith('/mobile'), 'Preview format must be shareable in URL');
  await page.locator('.reader-canvas').evaluate(el => { el.scrollTop = 400; });
  assert(await page.locator('.reader-canvas').evaluate(el => el.scrollTop > 0), 'Full-page PNG must scroll');
  await page.locator('.project-dialog').screenshot({ path: evidence + 'react-reader-desktop.png' });
  await page.keyboard.press('Escape');
  assert(await page.locator('dialog[open]').count() === 0, 'Escape must close reader');
  assert(await page.evaluate(() => document.body.style.overflow !== 'hidden'), 'Closing reader must restore background scroll');
  results.desktop.reader = { modes: true, deepLink: true, verticalScroll: true, escape: true, scrollRestored: true };
  await page.locator('#sistemas').scrollIntoViewIfNeeded();
  await page.locator('.system-case summary').nth(1).click();
  assert(await page.locator('.system-case').nth(1).getAttribute('open') !== null, 'System case must expand');
  await page.locator('#sistemas').screenshot({ path: evidence + 'react-systems-desktop.png', style: captureStyle });
  await page.locator('#sobre').scrollIntoViewIfNeeded();
  await page.locator('#anfc img').evaluate(el => el.decode());
  assert(await page.locator('#anfc img').getAttribute('src') === '/assets/brand/anfc-original.png', 'Company module must use original A-NFC mark');
  assert(await page.locator('#anfc').getByRole('link', { name: 'Conheça a A-NFC' }).getAttribute('href') === 'https://anfc.shop', 'Company CTA must lead to A-NFC');
  await page.locator('#anfc').screenshot({ path: evidence + 'react-anfc-desktop.png', style: captureStyle });
  await page.locator('.earlier-career summary').click();
  assert(await page.getByText('Auxiliar de Produção', { exact: true }).isVisible(), 'Previous career must expand');
  await page.locator('#sobre').screenshot({ path: evidence + 'react-about-desktop.png', style: captureStyle });
  await page.locator('#contato').screenshot({ path: evidence + 'react-contact-desktop.png', style: captureStyle });
  results.desktop.systemDetails = true;
  results.desktop.careerDetails = true;
  results.desktop.companyBrand = true;
  await page.locator('.faq-list summary').first().click();
  assert(await page.locator('.faq-list details').first().getAttribute('open') !== null, 'FAQ must expand');
  await page.locator('#servicos').getByRole('button', { name: 'Conversar sobre seu projeto' }).first().click();
  await page.getByRole('dialog', { name: 'Rikelme Batista', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Fechar chat', exact: true }).click();
  results.desktop.quoteCta = true;
  await page.locator('#servicos').screenshot({ path: evidence + 'react-services-desktop.png', style: captureStyle });
  await page.locator('#processo').screenshot({ path: evidence + 'react-process-desktop.png', style: captureStyle });
  for (const width of [360, 390, 768, 1366]) {
    await page.setViewportSize({ width, height: width < 768 ? 844 : 768 });
    await page.goto(baseUrl, { waitUntil: 'networkidle' });
    await page.waitForFunction(() => [...document.querySelectorAll('.hero-copy > div')].every(el => Number(getComputedStyle(el).opacity) > 0.99));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Page overflows at ${width}px`);
    const cta = await page.getByRole('button', { name: 'Começar um projeto', exact: true }).first().boundingBox();
    assert(cta && cta.y + cta.height <= (width < 768 ? 844 : 768), `Hero CTA must fit at ${width}px`);
    if (width === 390) {
      await page.screenshot({ path: evidence + 'react-hero-mobile.png' });
      await page.getByRole('button', { name: 'Abrir menu' }).click();
      assert(await page.locator('#primary-nav').isVisible(), 'Mobile navigation must open');
      await page.locator('#primary-nav').getByRole('link', { name: 'Projetos', exact: true }).click();
      assert(!(await page.locator('#primary-nav').isVisible()), 'Navigation must close after selection');
      await page.locator('.work-item').first().screenshot({ path: evidence + 'react-project-mobile.png' });
      const mobileCapture = page.locator('.showcase-card').first().locator('.carousel-slide[data-current="true"] .showcase-capture');
      await mobileCapture.evaluate(el => window.scrollBy(0, el.getBoundingClientRect().top - 160));
      const box = await mobileCapture.boundingBox();
      const cdp = await page.context().newCDPSession(page);
      await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true });
      const touchY = box.y + 100;
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 285, y: touchY }] });
      for (let step = 1; step <= 12; step++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 285 - step * 18, y: touchY }] });
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
      await page.waitForFunction(() => document.querySelector('.showcase-track').scrollLeft > 80);
      await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: false });
      await cdp.detach();
      await track.evaluate(el => el.scrollTo({ left: 0, behavior: 'instant' }));
      await page.getByRole('link', { name: 'Explorar projeto Alice Vieira', exact: true }).first().click();
      await page.locator('.project-dialog').getByRole('button', { name: 'Celular', exact: true }).click();
      await page.locator('.reader-canvas img').evaluate(el => el.decode());
      await page.locator('.project-dialog').screenshot({ path: evidence + 'react-reader-mobile.png' });
      await page.getByRole('button', { name: 'Fechar prévia do projeto' }).click();
      await page.getByRole('button', { name: 'Abrir menu' }).click();
      await page.keyboard.press('Escape');
      assert(!(await page.locator('#primary-nav').isVisible()), 'Escape must close mobile menu');
      await page.locator('#anfc').scrollIntoViewIfNeeded();
      await page.locator('#anfc img').evaluate(el => el.decode());
      await page.locator('#anfc').screenshot({ path: evidence + 'react-anfc-mobile.png', style: captureStyle });
      results.mobile = { menu: true, escape: true, reader: true, touchSwipe: true };
    }
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  assert(await page.locator('.stack-static li').count() === 14, 'Reduced motion must show the static technology list');
  results.reducedMotion = true;
  await page.addScriptTag({ path: 'node_modules/axe-core/axe.min.js' });
  const audit = await page.evaluate(async () => await axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } }));
  results.accessibility = audit.violations.map(item => ({ id: item.id, impact: item.impact, nodes: item.nodes.map(node => node.target) }));
  results.pageErrors = errors;
  assert(errors.length === 0, 'Unexpected JavaScript errors: ' + errors.join(', '));
  return results;
}
